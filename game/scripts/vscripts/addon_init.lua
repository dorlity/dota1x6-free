function IsValid(...)
for i = 1, select("#", ...) do
    local entity = select(i, ...)
    if not entity or not entity.IsNull or entity:IsNull() then
        return false
    end
end
return true
end

function IsRadiant(name)
if name == "2" or name == "6" or (name == "7" and IsSoloMode()) or name == "edge_teleport_1" then
    return true
end
return false
end

